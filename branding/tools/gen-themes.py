def gen_shortcuts() -> None:
    """Global shortcuts for new users (skel) and the tiling toggle launcher.

    kglobalacceld opens kglobalshortcutsrc as KConfig::SimpleConfig, so
    /etc/xdg/kglobalshortcutsrc and ~/.config/kdedefaults are NOT read: the
    defaults have to be in the user's own file (copied from /etc/skel).
    Entry format: "<active keys, tab separated>,<default keys>,<friendly name>";
    service (.desktop) components use plain "_launch=<keys>".
    """
    lines = [header("#", "Default global shortcuts for new monOS users (System Settings > Shortcuts).")]
    lines.append("[kwin]")
    for i in range(1, VIRTUAL_DESKTOPS + 1):
        default = f"Meta+F{i}\\tCtrl+F{i}"
        lines.append(f"Switch to Desktop {i}=Meta+{i}\\t{default},{default},Switch to Desktop {i}")
    for i in range(1, VIRTUAL_DESKTOPS + 1):
        keys = "\\t".join(f"Meta+{sym}" for sym in SHIFTED_DIGITS[i])
        lines.append(f"Window to Desktop {i}={keys},none,Window to Desktop {i}")
    lines.append("KrohnkiteSetMaster=Meta+Shift+Return,Meta+Return,Krohnkite: Set master")
    lines.append("")
    lines.append("# Meta+1..4 switch virtual desktops instead of activating task manager entries.")
    lines.append("[plasmashell]")
    for i in range(1, VIRTUAL_DESKTOPS + 1):
        lines.append(
            f"activate task manager entry {i}=none,Meta+{i},Activate Task Manager Entry {i}"
        )
    lines.append("")
    for desktop_file, keys in APP_SHORTCUTS.items():
        lines.append(f"[services][{desktop_file}]")
        lines.append(f"_launch={keys}")
        lines.append("")
    write(SKEL_CFG / "kglobalshortcutsrc", "\n".join(lines))

    # Default shortcut for every user via X-KDE-Shortcuts (kglobalacceld
    # registers applications that declare it).
    toggle = f"""[Desktop Entry]
# {GEN_NOTE}
Type=Application
Name=Toggle Tiling (Krohnkite)
Comment=Turn KWin dynamic tiling on or off
Exec=/usr/local/bin/monos-tiling-toggle
Icon=dialog-tile-clones
Terminal=false
StartupNotify=false
Categories=Utility;
Keywords=tiling;krohnkite;kwin;windows;
X-KDE-Shortcuts={TILING_TOGGLE_SHORTCUT}
"""
    write(AIROOTFS / "usr" / "local" / "share" / "applications" / "monos-tiling-toggle.desktop", toggle)


