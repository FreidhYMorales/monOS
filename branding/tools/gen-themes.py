def argb(alpha: int, c: str) -> str:
    return f"#{alpha:02x}{bare(c)}"


def gen_syslinux(p: Palette) -> None:
    u, x = p.ui, p.ansi
    # vesamenu: "MENU COLOR <item> <ansi> <fg #AARRGGBB> <bg #AARRGGBB> <shadow>"
    block = f"""MENU COLOR screen       37;40   {argb(0x00, u['bg'])} {argb(0x00, u['bg'])} none
MENU COLOR border       30;44   {argb(0x00, u['bg'])} {argb(0x00, u['bg'])} none
MENU COLOR title        1;36;44 {argb(0xff, x['blue'])} {argb(0x00, u['bg'])} none
MENU COLOR sel          7;37;40 {argb(0xff, u['accent-fg'])} {argb(0xff, u['accent'])} none
MENU COLOR hotsel       1;7;37;40 {argb(0xff, u['accent-fg'])} {argb(0xff, u['accent'])} none
MENU COLOR unsel        37;44   {argb(0xff, x['white'])} {argb(0x00, u['bg'])} none
MENU COLOR hotkey       1;37;44 {argb(0xff, x['bright-blue'])} {argb(0x00, u['bg'])} none
MENU COLOR help         37;40   {argb(0xff, u['fg-dim'])} {argb(0x00, u['bg'])} none
MENU COLOR timeout_msg  37;40   {argb(0xff, u['muted'])} {argb(0x00, u['bg'])} none
MENU COLOR timeout      1;37;40 {argb(0xff, x['bright-blue'])} {argb(0x00, u['bg'])} none
MENU COLOR msg07        37;40   {argb(0xff, u['fg'])} {argb(0x00, u['bg'])} none
MENU COLOR tabmsg       31;40   {argb(0xff, u['muted'])} {argb(0x00, u['bg'])} none
MENU COLOR cmdmark      1;36;40 {argb(0xff, x['blue'])} {argb(0x00, u['bg'])} none
MENU COLOR cmdline      37;40   {argb(0xff, u['fg'])} {argb(0x00, u['bg'])} none"""
    path = PROFILE / "syslinux" / "archiso_head.cfg"
    text = path.read_text(encoding="utf-8")
    # Drop the original MENU COLOR lines once; later runs replace the block.
    if BEGIN_MARK not in text:
        text = re.sub(r"^MENU COLOR .*\n", "", text, flags=re.M)
        text = text.replace("MENU CLEAR", f"# {BEGIN_MARK}\n# {END_MARK}\n\nMENU CLEAR", 1)
    text = replace_block(text, block)
    write(path, text)


def gen_calamares(p: Palette) -> None:
    u = p.ui
    branding = AIROOTFS / "etc" / "calamares" / "branding" / "monos"
    desc_path = branding / "branding.desc"
    desc = desc_path.read_text(encoding="utf-8")
    style = {
        "SidebarBackground": u["bg"],
        "SidebarText": u["fg"],
        "SidebarTextCurrent": u["accent-fg"],
        "SidebarBackgroundCurrent": u["accent"],
    }
    for key, value in style.items():
        desc, n = re.subn(rf'^(\s*{key}:\s*)"[^"]*"', rf'\g<1>"{value}"', desc, flags=re.M)
        if n != 1:
            raise SystemExit(f"error: {desc_path}: style key {key} not found exactly once")
    desc = re.sub(
        r"^# Colors match the logo:.*$",
        f"# Colors come from branding/palette/monos.toml (gen-themes.py rewrites the style keys).",
        desc,
        flags=re.M,
    )
    write(desc_path, desc)

    qml_path = branding / "show.qml"
    qml = qml_path.read_text(encoding="utf-8")
    props = {
        "bgColor": u["bg"],
        "accentColor": u["accent-text"],
        "fgColor": u["fg"],
    }
    for key, value in props.items():
        qml, n = re.subn(
            rf'(readonly property color {key}: )"[^"]*"', rf'\g<1>"{value}"', qml
        )
        if n != 1:
            raise SystemExit(f"error: {qml_path}: property {key} not found exactly once")
    write(qml_path, qml)


def gen_os_release(p: Palette) -> None:
    """ANSI_COLOR (used by systemd and fastfetch for the distro name)."""
    path = AIROOTFS / "etc" / "os-release"
    r, g, b = rgb(p.ui["accent-text"])
    text, n = re.subn(r'^ANSI_COLOR=.*$', f'ANSI_COLOR="38;2;{r};{g};{b}"', path.read_text(encoding="utf-8"), flags=re.M)
    if n != 1:
        raise SystemExit(f"error: {path}: ANSI_COLOR not found exactly once")
    write(path, text)


