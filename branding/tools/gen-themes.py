def cterm_index(p: Palette, hex_color: str | None) -> str:
    """Map a palette color to the closest of the 16 terminal colors.

    The monOS terminals use exactly the ANSI palette of monos.toml, so a
    16-color fallback (Linux console, no termguicolors) still looks right.
    """
    if hex_color is None:
        return "NONE"
    if hex_color.upper() in (p.ui["bg"].upper(), p.ui["fg"].upper()):
        return "NONE"  # the terminal's default background/foreground
    table = p.ansi16()
    for i, color in enumerate(table):
        if color.upper() == hex_color.upper():
            return str(i)

    def dist(a: str, b: str) -> int:
        return sum((ca - cb) ** 2 for ca, cb in zip(rgb(a), rgb(b)))

    return str(min(range(16), key=lambda i: dist(hex_color, table[i])))


def gen_vim_colors(p: Palette) -> None:
    common, nvim = editor_groups(p)
    x, u = p.ansi16(), p.ui

    def vim_line(name: str, spec: dict) -> str:
        if "link" in spec:
            return f"hi! link {name} {spec['link']}"
        style = ",".join(spec["style"]) or "NONE"
        cstyle = ",".join(s if s != "undercurl" else "underline" for s in spec["style"]) or "NONE"
        parts = [
            f"hi {name}",
            f"guifg={spec['fg'] or 'NONE'}",
            f"guibg={spec['bg'] or 'NONE'}",
            f"gui={style}",
            f"ctermfg={cterm_index(p, spec['fg'])}",
            f"ctermbg={cterm_index(p, spec['bg'])}",
            f"cterm={cstyle}",
        ]
        if spec.get("sp"):
            parts.append(f"guisp={spec['sp']}")
        return " ".join(parts)

    common_lines = "\n".join(vim_line(n, s) for n, s in common.items())
    nvim_lines = "\n".join("  " + vim_line(n, s) for n, s in nvim.items() if not n.startswith("@"))
    terminal = ", ".join(f"'{c}'" for c in x)
    colors = f"""{header('"')}" monOS colorscheme for Vim (and Neovim, which prefers colors/monos.lua).
" Uses 24-bit colors with 'termguicolors' or in gVim, and the 16 terminal
" colors otherwise (the monOS terminals use the same palette).

set background=dark
hi clear
if exists('syntax_on')
  syntax reset
endif
let g:colors_name = 'monos'

let g:terminal_ansi_colors = [{terminal}]

{common_lines}
if has('nvim')
{nvim_lines}
endif
"""
    write(AIROOTFS / "usr" / "share" / "vim" / "vimfiles" / "colors" / "monos.vim", colors)

    plugin = f"""{header('"')}" monOS: use the monos colorscheme when the user configuration did not
" choose one. Any `colorscheme` command in ~/.vimrc runs before this file,
" sets g:colors_name and therefore wins. Remove this behavior with
"   let g:monos_no_default_colorscheme = 1
" in ~/.vimrc.
if has('nvim') || exists('g:monos_no_default_colorscheme') || exists('g:colors_name')
  finish
endif
if has('gui_running') || &termguicolors || &t_Co >= 16
  silent! colorscheme monos
endif
"""
    write(AIROOTFS / "usr" / "share" / "vim" / "vimfiles" / "plugin" / "monos.vim", plugin)

    # Neovim (Lua)
    def lua_spec(spec: dict, name: str) -> str:
        if "link" in spec:
            return f'  ["{name}"] = {{ link = "{spec["link"]}" }},'
        items = []
        if spec["fg"]:
            items.append(f'fg = "{spec["fg"]}"')
        if spec["bg"]:
            items.append(f'bg = "{spec["bg"]}"')
        if spec.get("sp"):
            items.append(f'sp = "{spec["sp"]}"')
        cfg = cterm_index(p, spec["fg"])
        cbg = cterm_index(p, spec["bg"])
        if cfg != "NONE":
            items.append(f"ctermfg = {cfg}")
        if cbg != "NONE":
            items.append(f"ctermbg = {cbg}")
        for s in spec["style"]:
            items.append(f"{s} = true")
        return f'  ["{name}"] = {{ {", ".join(items)} }},'

    groups = {**common, **nvim}
    lua_groups = "\n".join(lua_spec(s, n) for n, s in groups.items())
    terminal_lua = "\n".join(f'vim.g.terminal_color_{i} = "{c}"' for i, c in enumerate(x))
    lua = f"""{header('--')}-- monOS colorscheme for Neovim: `:colorscheme monos`.
-- 24-bit colors with 'termguicolors' (default in kitty/foot), otherwise the
-- 16 terminal colors (the monOS terminals use the same palette).

vim.cmd("highlight clear")
if vim.fn.exists("syntax_on") == 1 then
  vim.cmd("syntax reset")
end
vim.o.background = "dark"
vim.g.colors_name = "monos"

local groups = {{
{lua_groups}
}}

for name, spec in pairs(groups) do
  vim.api.nvim_set_hl(0, name, spec)
end

{terminal_lua}
"""
    nvim_site = AIROOTFS / "usr" / "local" / "share" / "nvim" / "site"
    write(nvim_site / "colors" / "monos.lua", lua)

    nvim_plugin = f"""{header('--')}-- monOS: use the monos colorscheme when the user configuration did not choose
-- one. init.lua/init.vim run before plugin/ files, so any `colorscheme` there
-- (or in a plugin manager that loads it during init) wins. Disable with
--   vim.g.monos_no_default_colorscheme = true
-- in init.lua.
if vim.g.monos_no_default_colorscheme or vim.g.colors_name then
  return
end
pcall(vim.cmd.colorscheme, "monos")
"""
    write(nvim_site / "plugin" / "monos.lua", nvim_plugin)


