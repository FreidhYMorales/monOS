# --------------------------------------------------------------------------
# Palette helpers
# --------------------------------------------------------------------------
class Palette:
    def __init__(self, data: dict):
        self.data = data
        self.brand = data["brand"]
        self.ui = data["ui"]
        self.ansi = data["ansi"]
        # monOS Light ([light.ui] / [light.ansi]): same keys as [ui] / [ansi].
        self.light_ui = data["light"]["ui"]
        self.light_ansi = data["light"]["ansi"]
        sections = {
            "brand": self.brand,
            "ui": self.ui,
            "ansi": self.ansi,
            "light.ui": self.light_ui,
            "light.ansi": self.light_ansi,
        }
        for section, values in sections.items():
            for key, value in values.items():
                if not re.fullmatch(r"#[0-9A-Fa-f]{6}", value):
                    raise SystemExit(f"error: {section}.{key} = {value!r} is not #RRGGBB")
        for key in self.ui:
            if key not in self.light_ui:
                raise SystemExit(f"error: light.ui.{key} is missing")
        for key in self.ansi:
            if key not in self.light_ansi:
                raise SystemExit(f"error: light.ansi.{key} is missing")

    def ansi16(self) -> list[str]:
        normal = [self.ansi[n] for n in ANSI_NAMES]
        bright = [self.ansi[f"bright-{n}"] for n in ANSI_NAMES]
        return normal + bright

    def __getitem__(self, key: str) -> str:
        """Look up 'ui.fg', 'ansi.red', 'brand.blue', 'light.ui.fg'."""
        if key.startswith("light."):
            section, name = key[len("light."):].split(".", 1)
            return self.data["light"][section][name]
        section, name = key.split(".", 1)
        return self.data[section][name]


def rgb(hex_color: str) -> tuple[int, int, int]:
    h = hex_color.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def kde_rgb(hex_color: str) -> str:
    return ",".join(str(c) for c in rgb(hex_color))


def bare(hex_color: str) -> str:
    return hex_color.lstrip("#").lower()


def mix(a: str, b: str, t: float) -> str:
    ra, ga, ba = rgb(a)
    rb, gb, bb = rgb(b)
    return "#{:02X}{:02X}{:02X}".format(
        round(ra + (rb - ra) * t), round(ga + (gb - ga) * t), round(ba + (bb - ba) * t)
    )


def luminance(hex_color: str) -> float:
    def channel(c: int) -> float:
        c = c / 255
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = rgb(hex_color)
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def contrast(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


# --------------------------------------------------------------------------
# Output helpers
# --------------------------------------------------------------------------
WRITTEN: list[Path] = []
CHANGED: list[Path] = []


def write(path: Path, content: str) -> None:
    if not content.endswith("\n"):
        content += "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != content:
        path.write_text(content, encoding="utf-8")
        CHANGED.append(path)
    WRITTEN.append(path)


def header(prefix: str, extra: str = "") -> str:
    lines = [f"{prefix} {GEN_NOTE}", f"{prefix} Source: branding/palette/monos.toml"]
    if extra:
        lines += [f"{prefix} {line}" if line else prefix for line in extra.splitlines()]
    return "\n".join(lines) + "\n"


def replace_block(text: str, block: str, prefix: str = "#") -> str:
    """Replace (or append) the generated block delimited by the markers."""
    begin = f"{prefix} {BEGIN_MARK}"
    end = f"{prefix} {END_MARK}"
    new = f"{begin}\n{block.rstrip()}\n{end}"
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if pattern.search(text):
        return pattern.sub(lambda _m: new, text)
    return text.rstrip("\n") + "\n\n" + new + "\n"


