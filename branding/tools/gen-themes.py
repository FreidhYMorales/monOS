WRITTEN: list[Path] = []
CHANGED: list[Path] = []


def write(path: Path, content: str) -> None:
    if not content.endswith("\n"):
        content += "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    old = path.read_text(encoding="utf-8") if path.exists() else None
    if old != content:
        path.write_text(content, encoding="utf-8")
        CHANGED.append(path)
    WRITTEN.append(path)


def header(prefix: str, extra: str = "") -> str:
    lines = [f"{prefix} {GEN_NOTE}", f"{prefix} Source: branding/palette/monos.toml"]
    if extra:
        lines += [f"{prefix} {line}" if line else prefix for line in extra.splitlines()]
    return "\n".join(lines) + "\n"


def replace_block(text: str, block: str, prefix: str = "#") -> str:
    """Replace (or append) the generated block delimited by the markers."""
    begin = f"{prefix} {BEGIN_MARK}"
    end = f"{prefix} {END_MARK}"
    new = f"{begin}\n{block.rstrip()}\n{end}"
    pattern = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    if pattern.search(text):
        return pattern.sub(lambda _m: new, text)
    return text.rstrip("\n") + "\n\n" + new + "\n"


# --------------------------------------------------------------------------
# Contrast report
# --------------------------------------------------------------------------
def contrast_report(p: Palette) -> tuple[list[str], bool]:
    bg = p.ui["bg"]
    rows = []
    ok = True
    checks = [
        ("ui.fg", 7.0),
        ("ui.fg-dim", 4.5),
        ("ui.muted", 4.5),
        ("ui.accent-text", 4.5),
        ("ui.violet-text", 4.5),
    ]
    checks += [(f"ansi.{n}", 4.5) for n in ANSI_NAMES if n != "black"]
    checks += [(f"ansi.bright-{n}", 4.5) for n in ANSI_NAMES]
    for key, target in checks:
        ratio = contrast(p[key], bg)
        passed = ratio >= target
        ok &= passed
        rows.append(f"  {key:22} {p[key]}  {ratio:5.2f}:1  (>= {target}) {'ok' if passed else 'FAIL'}")
    pairs = [
        ("ui.accent-fg on ui.accent", p.ui["accent-fg"], p.ui["accent"], 4.5),
        ("ui.fg on ui.selection", p.ui["fg"], p.ui["selection"], 7.0),
        ("ui.fg on ui.surface2", p.ui["fg"], p.ui["surface2"], 7.0),
        ("ui.fg-dim on ui.surface2", p.ui["fg-dim"], p.ui["surface2"], 4.5),
        ("ui.fg on ui.overlay", p.ui["fg"], p.ui["overlay"], 7.0),
        ("brand.blue on ui.bg (non-text)", p.brand["blue"], bg, 3.0),
    ]
    for label, fg, back, target in pairs:
        ratio = contrast(fg, back)
        passed = ratio >= target
        ok &= passed
        rows.append(f"  {label:34} {ratio:5.2f}:1  (>= {target}) {'ok' if passed else 'FAIL'}")
    return rows, ok


