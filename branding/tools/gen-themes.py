def read_grub_font_names() -> dict[str, str]:
    """Names of the PF2 fonts produced by install-branding.sh (NAME section)."""
    theme_dir = AIROOTFS / "usr" / "share" / "grub" / "themes" / "monos"
    wanted = {
        "regular": "noto-sans-regular-18.pf2",
        "bold": "noto-sans-bold-18.pf2",
        "small": "noto-sans-regular-14.pf2",
        "mono": "noto-sans-mono-regular-16.pf2",
    }
    # GRUB always has "Unifont Regular 16" when it only has unicode.pf2.
    names = {k: "Unifont Regular 16" for k in wanted}
    for key, filename in wanted.items():
        path = theme_dir / filename
        if not path.exists():
            continue
        data = path.read_bytes()
        idx = data.find(b"NAME")
        if idx < 0:
            continue
        length = int.from_bytes(data[idx + 4 : idx + 8], "big")
        names[key] = data[idx + 8 : idx + 8 + length].rstrip(b"\0").decode()
    return names


