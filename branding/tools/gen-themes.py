def kde_color_groups(p: Palette, light: bool = False) -> str:
    """KDE color scheme groups for MonosDark (default) or MonosLight."""
    u, x = (p.light_ui, p.light_ansi) if light else (p.ui, p.ansi)

    def fg_set(ui: dict, ansi: dict) -> dict:
        return {
            "ForegroundNormal": ui["fg"],
            "ForegroundInactive": ui["fg-dim"],
            "ForegroundActive": ansi["blue"],
            "ForegroundLink": ansi["blue"],
            "ForegroundVisited": ansi["bright-magenta"] if not light else ansi["magenta"],
            "ForegroundNegative": ansi["red"],
            "ForegroundNeutral": ansi["yellow"],
            "ForegroundPositive": ansi["green"],
            "DecorationFocus": ui["accent"],
            "DecorationHover": ansi["blue"],
        }

    fg_common = fg_set(u, x)
    if light:
        # Light: views are the lightest surface, windows/headers one step
        # darker, buttons light on the window color (like Breeze Light).
        groups = {
            "Colors:Button": {"BackgroundNormal": u["bg"], "BackgroundAlternate": u["selection"]},
            "Colors:Header": {"BackgroundNormal": u["surface2"], "BackgroundAlternate": u["surface"]},
            "Colors:Header][Inactive": {"BackgroundNormal": u["surface"], "BackgroundAlternate": u["surface2"]},
            "Colors:Selection": {"BackgroundNormal": u["accent"], "BackgroundAlternate": u["selection"]},
            "Colors:Tooltip": {"BackgroundNormal": u["bg"], "BackgroundAlternate": u["surface"]},
            "Colors:View": {"BackgroundNormal": u["bg"], "BackgroundAlternate": u["surface"]},
            "Colors:Window": {"BackgroundNormal": u["surface2"], "BackgroundAlternate": u["overlay"]},
        }
    else:
        groups = {
            "Colors:Button": {"BackgroundNormal": u["overlay"], "BackgroundAlternate": u["selection"]},
            "Colors:Complementary": {"BackgroundNormal": u["bg"], "BackgroundAlternate": u["surface"]},
            "Colors:Header": {"BackgroundNormal": u["surface2"], "BackgroundAlternate": u["surface"]},
            "Colors:Header][Inactive": {"BackgroundNormal": u["surface"], "BackgroundAlternate": u["surface2"]},
            "Colors:Selection": {"BackgroundNormal": u["accent"], "BackgroundAlternate": u["selection"]},
            "Colors:Tooltip": {"BackgroundNormal": u["surface2"], "BackgroundAlternate": u["surface"]},
            "Colors:View": {"BackgroundNormal": u["surface"], "BackgroundAlternate": mix(u["surface"], u["surface2"], 0.5)},
            "Colors:Window": {"BackgroundNormal": u["surface2"], "BackgroundAlternate": u["overlay"]},
        }
    # Text on the brand-blue selection: same in both variants (the dark
    # palette's bright colors are the readable ones on blue).
    selection_fg = {
        "ForegroundNormal": u["accent-fg"],
        "ForegroundInactive": mix(u["accent-fg"], u["accent"], 0.3),
        "ForegroundActive": u["accent-fg"],
        "ForegroundLink": p.ansi["bright-yellow"],
        "ForegroundVisited": p.ansi["bright-magenta"],
        "ForegroundNegative": p.ansi["bright-red"],
        "ForegroundNeutral": p.ansi["bright-yellow"],
        "ForegroundPositive": p.ansi["bright-green"],
    }
    out = [
        "[ColorEffects:Disabled]",
        f"Color={kde_rgb(u['surface2'])}",
        "ColorAmount=0",
        "ColorEffect=0",
        "ContrastAmount=0.65",
        "ContrastEffect=1",
        "IntensityAmount=0.1",
        "IntensityEffect=2",
        "",
        "[ColorEffects:Inactive]",
        "ChangeSelectionColor=true",
        f"Color={kde_rgb(u['muted'])}",
        "ColorAmount=0.025",
        "ColorEffect=2",
        "ContrastAmount=0.1",
        "ContrastEffect=2",
        "Enable=false",
        "IntensityAmount=0",
        "IntensityEffect=0",
        "",
    ]
    for name, bgs in groups.items():
        values = dict(fg_common)
        if name == "Colors:Selection":
            values.update(selection_fg)
        values.update(bgs)
        out.append(f"[{name}]")
        out += [f"{k}={kde_rgb(v)}" for k, v in sorted(values.items())]
        out.append("")
    if light:
        # Complementary areas (logout screen, OSDs over the desktop) stay dark,
        # as in Breeze Light.
        values = fg_set(p.ui, p.ansi)
        values.update({"BackgroundNormal": p.ui["bg"], "BackgroundAlternate": p.ui["surface"]})
        out.append("[Colors:Complementary]")
        out += [f"{k}={kde_rgb(v)}" for k, v in sorted(values.items())]
        out.append("")
    out += [
        "[WM]",
        f"activeBackground={kde_rgb(u['surface2'])}",
        f"activeBlend={kde_rgb(u['fg'])}",
        f"activeForeground={kde_rgb(u['fg'])}",
        f"inactiveBackground={kde_rgb(u['surface'])}",
        f"inactiveBlend={kde_rgb(u['fg-dim'])}",
        f"inactiveForeground={kde_rgb(u['fg-dim'])}",
    ]
    return "\n".join(out) + "\n"


def colorizer_color(system_color: str, alpha: float, color_set: str = "View") -> dict:
    """A Panel Colorizer color taken from the Plasma color scheme.

    sourceType 1 = Kirigami theme color (package/contents/ui/code/utils.js
    getColor); MonosDark/MonosLight map View background to ui.surface /
    light.ui.bg, View highlight to the brand accent and Window alternate
    background to ui.overlay / light.ui.overlay. Following the scheme keeps
    the islands right when only the color scheme changes (e.g. Plasma's
    day/night switching)."""
    return {
        "enabled": True,
        "sourceType": 1,
        "systemColor": system_color,
        "systemColorSet": color_set,
        "alpha": alpha,
    }


def colorizer_settings(kind: str, light: bool) -> dict:
    """Panel Colorizer `globalSettings` for the top bar ("islands") or the dock.

    Only the keys monOS changes are written; the widget fills in the rest from
    its defaults (Utils.mergeConfigs over Globals.defaultConfig, v8.0.0)."""
    bg_alpha = 0.85 if light else 0.88
    border_alpha = 0.35 if light else 0.30
    shadow_alpha = 0.10 if light else 0.35
    surface = {
        "enabled": True,
        "blurBehind": True,
        "backgroundColor": colorizer_color("backgroundColor", bg_alpha),
        "radius": {
            "enabled": True,
            "corner": {c: PANEL_RADIUS for c in ("topLeft", "topRight", "bottomRight", "bottomLeft")},
        },
        "border": {
            "enabled": True,
            "customSides": False,
            "width": 1,
            "color": colorizer_color("highlightColor", border_alpha),
        },
        "shadow": {
            "background": {
                "enabled": True,
                "color": {"enabled": True, "sourceType": 0, "custom": "#000000", "alpha": shadow_alpha},
                "size": 6,
                "xOffset": 0,
                "yOffset": 1,
            },
        },
    }
    # The panel's own (Plasma theme) background is hidden: the colorizer
    # draws the rounded surfaces instead.
    native = {"background": {"enabled": False, "opacity": 1.0, "shadow": False}}
    if kind == "dock":
        return {"nativePanel": native, "panel": {"normal": surface}}

    # Islands: every widget gets the surface; Panel Colorizer merges the
    # widgets between two panel spacers into one rounded island. Horizontal
    # margins are the island's inner padding, vertical ones its gap to the
    # panel edge.
    island = dict(surface, spacing=4, opacity=1.0)
    island["margin"] = {"enabled": True, "side": {"left": 6, "right": 6, "top": 2, "bottom": 2}}
    # State overrides must repeat the plain (non-"enabled") keys, which are
    # not inherited from "normal" (Utils.getEffectiveSettings).
    plain = {"enabled": True, "blurBehind": True, "spacing": 4, "opacity": 1.0}
    hovered = dict(plain, backgroundColor=colorizer_color("alternateBackgroundColor", bg_alpha, "Window"))
    # Popup open (launcher, calendar, tray...): the widget's part of the
    # island gets an accent outline.
    expanded = dict(hovered)
    expanded["border"] = {
        "enabled": True,
        "customSides": False,
        "width": 1,
        "color": colorizer_color("highlightColor", 0.85),
    }
    return {
        "nativePanel": native,
        "widgets": {"normal": island, "hovered": hovered, "expanded": expanded},
    }


